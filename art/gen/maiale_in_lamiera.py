"""Maiale in Lamiera (Porcile, comune) — taglia S: un maiale tondo con una corazza di lamiera imbullonata sulla schiena
(due piastre con la giuntura e i bulloni). "Rumoroso quando cammina. Anche da fermo." Guarda a sinistra.

Disegnato a mano su griglia (forme partite da ellissi di shapes.py e poi ritoccate pixel per pixel).
Idle: il corpo sopra la riga SPLIT si abbassa di 1 px nei fotogrammi 1-2 (respiro), battito di ciglia al 3."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
from shapes import Sprite

LEGEND = {
    "o": "rosa_1", "h": "rosa_3", "c": "rosa_4", 
    "B": "ferro_1", "g": "ferro_2", "e": "ferro_4", "d": "ferro_5",
    "k": "inchiostro", "r": "radio_1",
}
#        0         1         2         3
#        01234567890123456789012345678901
BASE = """
................................
................................
................................
................................
................................
................................
................................
................................
................................
................................
................................
......oo....oo..................
.....ohho..ohho.................
.....ohcoooochoBBBBBB...........
....occcccccccoBddddddBB........
....occccccccchBdddddddgB.......
....occcccccchBddBddddgeeB......
....ockcccckchBdddddddgeBeB.....
...occkcccckchBeeeeeeegeeeB.....
..ohhhhcccccchBeeBeeeegeeeB.....
..ohohohccccchBeeeeeeegeeeB.o...
..ohhhhhcccchhBgggggggBgggBo.o..
...oooooccchhhhBBBBBBBhBBBhoo...
.....ohhhhhhhhhhhhhhhhhrhhho....
......ohhhhhhhhhhhhhhhhhhoo.....
.......ooohhooooooooohhoo.......
.........ohho......ohho.........
..........oo........oo..........
................................
................................
................................
................................
"""
EYES = [(6, 17), (6, 18), (11, 17), (11, 18)]
SPLIT = 22
DROP = (8, 18, 19, 20)        # colonne della griglia tolte per accorciare il corpo (taglia reale)          # le righe fino a questa si abbassano di 1 px quando respira
SHADOW = (15.0, 27.0, 9.5, 2.2)


def grid():
    rows = [r for r in BASE.strip("\n").split("\n")]
    assert len(rows) == 32 and all(len(r) == 32 for r in rows), [len(r) for r in rows]
    return [list(r) for r in rows]


def frame(i):
    g = grid()
    if i == 3:                                   # battito di ciglia: occhio chiuso = riga di contorno
        for (x, y) in EYES:
            g[y][x] = "c"
        g[18][6] = "o"; g[18][11] = "o"
    if i in (1, 2):                              # respiro: il corpo si schiaccia di 1 px
        for y in range(SPLIT, 0, -1):
            g[y] = list(g[y - 1])
    pad = len(DROP) // 2                         # toglie qualche colonna per stare nella taglia S/M e ricentra
    g = [["."] * pad + [c for x, c in enumerate(row) if x not in DROP] + ["."] * (len(DROP) - pad) for row in g]
    s = Sprite(32, 32)
    s.shadow(*SHADOW)
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != ".":
                s.px(x, y, LEGEND[ch])
    return s


if __name__ == "__main__":
    Sprite.save("maiale_in_lamiera", "game/assets/cards/maiale_in_lamiera.png", [frame(i) for i in range(4)],
                comment="Porcile, taglia S")
