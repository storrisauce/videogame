EYES_RIGHT = {(12, 16): "w", (13, 16): "k", (18, 16): "w", (19, 16): "k"}
EYES_LEFT = {(12, 16): "k", (13, 16): "w", (18, 16): "k", (19, 16): "w"}
SHADOW = (16, 30.6, 12.5, 1.8)


def grid():
    rows = BASE.strip("\n").split("\n")
    assert len(rows) == 32 and all(len(r) == 32 for r in rows), [(n, len(r)) for n, r in enumerate(rows) if len(r) != 32]
    return [list(r) for r in rows]


def frame(i):
    g = grid()
    eyes = EYES_LEFT if i in (2, 3) else EYES_RIGHT          # guarda di qua, poi di la'
    for (x, y), ch in eyes.items():
        g[y][x] = ch
    if i in (1, 2):                                          # l'aureola si accende
        for y in (2, 4):
            for x in range(32):
                if g[y][x] == "r" and 14 <= x <= 17:
                    g[y][x] = "R"
    s = Sprite(32, 32)
    s.shadow(*SHADOW)
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != ".":
                s.px(x, y, LEGEND[ch])
    return s


